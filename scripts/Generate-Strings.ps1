$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$resourcePath = Join-Path $projectRoot 'src/Sf6Prototype/Resources/Strings.resx'
$document = [xml](Get-Content -LiteralPath $resourcePath -Raw)
$properties = $document.root.data | Sort-Object name | ForEach-Object {
    if ($_.name -notmatch '^[A-Za-z][A-Za-z0-9_]*$') { throw "Invalid resource key: $($_.name)" }
    "    public static string $($_.name) => Localization.Get(nameof($($_.name)));"
}
$source = @('// <auto-generated />', '// Regenerate with scripts/Generate-Strings.ps1 after adding resource keys.', 'namespace Sf6Prototype;', '', 'public static class Strings', '{') + $properties + '}'
Set-Content -LiteralPath (Join-Path $projectRoot 'src/Sf6Prototype/Strings.g.cs') -Value $source -Encoding utf8
